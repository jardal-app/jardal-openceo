from typing import Any, Protocol


class BusinessWork(Protocol):
    provider: str
    is_enabled: bool

    async def create_ticket(self, *, ref: str, title: str, **kwargs: Any) -> dict[str, Any]: ...
    async def resolve_task(self, identifier: str) -> dict[str, Any]: ...
    async def search_tickets(self, **kwargs: Any) -> list[dict[str, Any]]: ...
    async def ensure_project(self, project_key: str, display_name: str | None = None) -> str | None: ...
    async def transition_status(self, identifier: str, to_status: str, **kwargs: Any) -> dict[str, Any]: ...
    async def aclose(self) -> None: ...


class BusinessApproval(Protocol):
    async def request_approval(self, request: dict[str, Any], *, key: str) -> dict[str, Any]: ...
    async def get_approval(self, identifier: str) -> dict[str, Any]: ...


class BusinessFinance(Protocol):
    async def record_income(self, operation: dict[str, Any], *, key: str) -> dict[str, Any]: ...
    async def record_expense(self, operation: dict[str, Any], *, key: str) -> dict[str, Any]: ...
    async def scope_summary(self, **filters: Any) -> dict[str, Any]: ...


class IdentityDelegation(Protocol):
    provider: str
    is_enabled: bool

    async def login(self, *, email: str, password: str) -> dict[str, Any]: ...
    async def introspect(self, user_token: str) -> dict[str, Any]: ...
    async def logout(self, user_token: str) -> None: ...
    async def aclose(self) -> None: ...
